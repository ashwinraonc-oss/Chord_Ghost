"""
Guitar chord voicings across the fretboard for every root note x chord quality
(minor, dim, augmented, 7th, maj7th, min7, dim7th, m7b5, sus2, sus4).

Format: each chord is a list of 10 voicings; each voicing is 6 values
[Low E, A, D, G, B, High E] giving the fret to play on that string, or -1 for
a string that is not played (muted).

Structure of the 10 voicings per chord (same method used throughout this chat):
  1. 'E-family' shape  - root on the Low E string, lowest position on the neck
  2. 'E-family' shape  - same shape, one octave up (+12 frets)
  3. 'A-family' shape  - root on the A string, lowest position (Low E muted)
  4. 'A-family' shape  - same shape, one octave up (+12 frets)
  5-7. top-3-string triads (G,B,High E) pulled from voicings 2, 3, 4
  8-10. middle-3-string triads (D,G,B) pulled from voicings 2, 3, 4

For the five 7th-family chord types (7th, maj7th, min7, dim7th, m7b5) each full
shape (1-4) contains all 4 chord tones; the 3-string subset voicings (5-10) can
only hold 3 notes, so some necessarily omit one of the 4 tones (never a wrong
note, just an incomplete one) -- same behavior as the partial triads seen with
D major and G major earlier in this chat. The same can happen for the plain
triad chord types (minor, dim, augmented, sus2, sus4) on a handful of shapes.

Frets are kept at or below 24 (standard guitar neck length) whenever possible.
For some roots, the octave-up voicings (2 and 4, and the triads pulled from
them) naturally want to sit a few frets beyond that; a string is muted instead
of reaching past fret 24 UNLESS doing so would leave a voicing with nothing
playable at all, in which case a small number of individual notes go past fret
24 (up to fret 27 in the most extreme case) so the voicing still contains real
chord tones. Everything played is still guaranteed to be a correct chord tone;
nothing here is ever a wrong note.

Generated and verified programmatically: every fretted note is confirmed to be a
real chord tone, and every shape's fret span stays within a realistic barre-chord
hand stretch (max 4 frets from the root fret).
"""

